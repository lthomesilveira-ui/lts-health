import assert from 'node:assert/strict';
globalThis.location={search:'?fixture=1'};
const {state}=await import('./src/core.js');
const {renderTimelineHub}=await import('./src/timeline-screen.js');
const {labSeriesChoice}=await import('./src/labs-layout-v2.js');
const sourceA={source_record_id:'synthetic-a',nutrition_date:'2026-01-15',source:'MyFitnessPal',calories_kcal:1234};
const sourceB={...sourceA,source_record_id:'synthetic-b',source:'Apple Health'};
state.data={nutrition:[sourceA,sourceB],workouts:[{source_record_id:'synthetic-workout',workout_date:'2026-01-15',workout_type:'Synthetic session',is_canonical:true}]};
state.domainStatus={nutrition:'ready',workouts:'ready'};state.errors={};state.ui={timelinePeriod:'all'};
const before=JSON.stringify(state.data),html=renderTimelineHub();
assert.match(html,/id="timelinePeriod" aria-label="Período do histórico"/);
assert.match(html,/id="timelineDomain" aria-label="Área do histórico"/);
const rows=[...html.matchAll(/<button[^>]+class="timelineContextJump"[^>]*>[\s\S]*?<\/button>/g)].map(m=>m[0]);
const foods=rows.filter(s=>s.includes('data-timeline-kind="nutrition"'));
assert.equal(foods.length,2,'both source records remain available');
assert.notEqual(foods[0].match(/aria-label="([^"]+)"/)[1],foods[1].match(/aria-label="([^"]+)"/)[1],'origins distinguish duplicate-looking choices');
assert.ok(foods.every(s=>s.includes('<small>')),'the distinction is visible, not just accessible');
assert.equal(JSON.stringify(state.data),before,'source labels never merge or mutate records');
const cohort={origin:'Synthetic lab',unit:'u',method:'Method A',all:[{collection_date:'2026-03-01'},{collection_date:'2026-01-01'}]};
assert.match(labSeriesChoice(cohort,0),/Method A · 01\/01\/2026–01\/03\/2026 \(2\)/);
assert.notEqual(labSeriesChoice(cohort,0),labSeriesChoice({...cohort,method:'Method B'},0));
assert.match(labSeriesChoice({origin:'',unit:'',method:'',all:[]},0),/Origem não informada · Sem unidade · Método não informado · Data não informada/);
console.log('Navigation content: source-distinguished timeline choices, labeled filters, dated/method-specific laboratory choices and unchanged originals passed.');
