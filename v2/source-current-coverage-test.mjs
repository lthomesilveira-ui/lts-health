import assert from 'node:assert/strict';
globalThis.location={search:'?fixture=1'};
const {state}=await import('./src/core.js');
const {sourceStatusFor,sourceCoverageFor,sourceTransportCoverageFor}=await import('./src/source-status.js');
const {renderDataHub}=await import('./src/data-screen.js');
state.data={nutrition:[],meals:[],sourceMetrics:[],polarSessions:[],workoutEvidence:[],workouts:[],uploads:[],previews:[],quality:[],labs:[],metrics:[]};
state.errors={};state.domainStatus=Object.fromEntries(Object.keys(state.data).map(key=>[key,'ready']));
const bridge=(date,source='MyFitnessPal',overrides={})=>({source_record_id:'health_auto_export:invented:'+date,metric_date:date,metric_type:'dietary_energy_kcal',value:1234,unit:'kcal',source_name:'Apple Saúde · '+source,source_family:'health_auto_export',canonical_status:'canonical',confidence:'authenticated_auto_export',...overrides});
state.data.nutrition=[{source_record_id:'invented-file',nutrition_date:'2001-04-01',source:'MyFitnessPal'}];
state.data.sourceMetrics=[bridge('2001-04-03'),bridge('2001-04-06','Origem não informada pelo Saúde'),bridge('2001-04-07','MyFitnessPal',{canonical_status:'candidate'}),bridge('2001-04-08','MyFitnessPal',{confidence:'unverified'})];
const before=JSON.stringify(state.data);
assert.equal(sourceStatusFor('myfitnesspal'),'ready');
assert.equal(sourceCoverageFor('myfitnesspal').confirmedDate,'2001-04-03');
assert.deepEqual(sourceTransportCoverageFor('myfitnesspal'),{fileDate:'2001-04-01',bridgeDate:'2001-04-03'});
let html=renderDataHub();
assert.ok(html.includes('Histórico por arquivo até: 01/04/2001'));
assert.ok(html.includes('Totais identificados como MyFitnessPal pelo Saúde do iPhone até: 03/04/2001'));
assert.ok(!html.includes('pelo Saúde do iPhone até: 06/04/2001'),'unknown source is not attributed to MyFitnessPal');
assert.equal(JSON.stringify(state.data),before,'coverage never merges or rewrites source records');
state.data.nutrition=[];
assert.equal(sourceStatusFor('myfitnesspal'),'ready','confirmed named bridge works without an old file');
state.domainStatus.sourceMetrics='error';
assert.equal(sourceStatusFor('myfitnesspal'),'unknown');
assert.equal(sourceTransportCoverageFor('myfitnesspal').bridgeDate,null,'failed cached source is not fresh evidence');
state.domainStatus.sourceMetrics='ready';state.data.sourceMetrics=[bridge('2001-04-06','Origem não informada pelo Saúde'),bridge('2001-04-09','MyFitnessPal',{metric_type:'dietary_water_ml'})];
assert.equal(sourceStatusFor('myfitnesspal'),'missing','water alone cannot assert food coverage');
state.data.workoutEvidence=[{source_record_id:'invented-linked',workout_date:'2001-04-02',source_family:'polar_flow',evidence_status:'confirmed'}];
state.data.polarSessions=[{source_record_id:'invented-provider-session',workout_date:'2001-04-05',source_name:'Polar Flow'}];
assert.equal(sourceCoverageFor('polar_flow').confirmedDate,'2001-04-05');
assert.equal(sourceStatusFor('polar_flow'),'ready');
assert.ok(renderDataHub().includes('Sessões recebidas do Polar até: 05/04/2001'));
assert.deepEqual(state.data.workouts,[],'provider session coverage never adds a canonical workout');
state.domainStatus.polarSessions='error';
assert.equal(sourceCoverageFor('polar_flow').confirmedDate,'2001-04-02','a failed provider read preserves only independently loaded linked evidence');
state.domainStatus.workoutEvidence='error';
assert.equal(sourceStatusFor('polar_flow'),'unknown');
assert.equal(sourceCoverageFor('polar_flow').confirmedDate,null);
state.data.uploads=[{id:'invented-upload',created_at:'2001-04-01',source_type:'myfitnesspal',status:'processed',original_filename:'Exporta%C3%A7%C3%A3o.zip'}];
assert.ok(renderDataHub().includes('Exportação.zip'));
state.data.uploads[0].original_filename='%3Cimg%20src%3Dx%3E';
assert.ok(renderDataHub().includes('&lt;img src=x&gt;'));
assert.ok(!renderDataHub().includes('<img src=x>'));
console.log('Named authenticated bridge, separate file/provider dates, unknown origins, failed reads, no duplicate workouts and safe filename display: passed.');
